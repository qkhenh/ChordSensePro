def test_cqt96_separates_fsharp2_and_g2_and_bass_hold_v6_4sec_reset():
    sr = 24000
    cqt_bank = HarmonicCQTFilterbankV6(sample_rate=sr).eval()
    n = sr * 5
    t = np.arange(n, dtype=np.float32) / sr
    # F#2 = 92.50 Hz (MIDI 42 -> low bin 36), G2 = 98.00 Hz (MIDI 43 -> low bin 38)
    wav_fs2 = torch.from_numpy(np.sin(2.0 * np.pi * 92.4986 * t)).unsqueeze(0)
    wav_g2 = torch.from_numpy(np.sin(2.0 * np.pi * 97.9989 * t)).unsqueeze(0)
    with torch.no_grad():
        c_fs2 = cqt_bank(wav_fs2)[0, 100:250].mean(dim=0)
        c_g2 = cqt_bank(wav_g2)[0, 100:250].mean(dim=0)
    assert c_fs2.shape == (96,)
    assert int(c_fs2.argmax().item()) == 36
    assert int(c_g2.argmax().item()) == 38

    # BassPedalHoldLayerV6: holds G (pc=7) for 3.4s (~255 frames) and resets within 1 block when F# (pc=6) strikes!
    hold = BassPedalHoldLayerV6(block_frames=12, n_taps=25, tau_frames=195.0).eval()
    phys_logits = torch.full((1, 320, 12), -6.0)
    reset_prob = torch.zeros((1, 320, 1))
    # Beat-1 G2 strike at frames 0..10
    phys_logits[0, 0:10, 7] = 5.0
    # New F#2 bass stepdown at frame 260 (3.47s later!)
    phys_logits[0, 260:275, 6] = 5.0
    reset_prob[0, 260:266, 0] = 0.99

    with torch.no_grad():
        bh = hold(phys_logits, bass_reset_prob=reset_prob)

    # Still strongly holding G at frame 240 (3.20s after beat 1 — solves Phep Mau mid-bar collapse!)
    assert float(bh[0, 240, 7].item()) > 0.25
    # Immediately resets old G and locks onto new F# at frame 268!
    assert float(bh[0, 268, 6].item()) > 0.85
    assert float(bh[0, 268, 7].item()) < 0.15


def test_dual_scale_passing_sustain_polyphonic_vs_single_melody():
    layer = DualScalePassingSustainLayer(short_frames=9, sustain_frames=39).eval()
    logits = torch.full((1, 150, 12), -5.0)
    # Fast 18-frame (~240ms) passing chord (C, E, G) at frames 50..68
    logits[0, 50:68, [0, 4, 7]] = 4.0
    # Case A: Single-note melody run (harm_onset_count = 0.8, p_bass_chg = 0.0)
    harm_1 = torch.zeros((1, 150, 1))
    harm_1[0, 50:54, 0] = 0.8
    # Case B: Polyphonic passing chord (harm_onset_count = 3.0)
    harm_3 = torch.zeros((1, 150, 1))
    harm_3[0, 50:54, 0] = 3.0
    # Case C: Bass-floor step change (harm_onset_count = 0.5, p_bass_chg = 0.95)
    bass_chg = torch.zeros((1, 150, 1))
    bass_chg[0, 50:54, 0] = 0.95

    with torch.no_grad():
        _, fast_mel, gate_mel = layer(logits, harm_onset_count=harm_1)
        _, fast_poly, gate_poly = layer(logits, harm_onset_count=harm_3)
        _, fast_bass, gate_bass = layer(logits, harm_onset_count=harm_1, p_bass_chg=bass_chg)

    assert float(gate_mel[0, 52, 0].item()) < 0.15
    assert float(fast_mel[0, 52, 4].item()) < 0.15
    assert float(gate_poly[0, 52, 0].item()) > 0.90
    assert float(fast_poly[0, 52, 4].item()) > 0.70
    assert float(gate_bass[0, 52, 0].item()) > 0.90
    assert float(fast_bass[0, 52, 4].item()) > 0.70


def test_dynamic_boundary_crf_pytorch_vs_numpy_parity_and_boundary_switch():
    torch.manual_seed(7)
    prior = build_functional_crf_prior_v6(stay_bonus=2.4)
    crf = DynamicBoundaryCRF(num_tags=169, stay_bonus=2.4, prior_matrix=prior).eval()

    em = torch.randn(2, 40, 169) * 0.6
    bnd = torch.zeros(2, 40)
    bnd[:, 15] = 0.95
    bnd[:, 28] = 0.90

    # Loss handles -100 unlabelled gaps cleanly
    targets = torch.randint(0, 169, (2, 40))
    targets[:, 5:10] = -100
    loss = crf(em, targets, boundary_prob=bnd)
    assert torch.isfinite(loss) and float(loss.item()) >= 0.0
    assert float(crf.prior_reg_loss().item()) == pytest.approx(0.0, abs=1e-6)

    # Exact PyTorch vs NumPy Viterbi parity
    path_pt = crf.decode(em, boundary_prob=bnd).numpy()
    stay_s, boost = crf._effective_params()
    for b_i in range(2):
        path_np = viterbi_dynamic_crf_numpy(
            em[b_i].numpy(),
            crf.transitions.detach().numpy(),
            crf.start_transitions.detach().numpy(),
            crf.end_transitions.detach().numpy(),
            boundary_prob=bnd[b_i].numpy(),
            boundary_stay_scale=float(stay_s.item()),
            boundary_trans_boost=float(boost.item()),
        )
        np.testing.assert_array_equal(path_pt[b_i], path_np)


